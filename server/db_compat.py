"""SQLite/PostgreSQL compatibility for SocialApp."""
import os
import re
import sqlite3


def postgres_enabled():
    return bool(os.environ.get("DATABASE_URL", "").strip())


def _hybrid_row_factory(cursor):
    names = [column.name for column in cursor.description] if cursor.description else []

    class HybridRow(dict):
        def __getitem__(self, key):
            if isinstance(key, int):
                key = names[key]
            return super().__getitem__(key)

    return lambda values: HybridRow(zip(names, values))


class CompatCursor:
    def __init__(self, cursor, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __iter__(self):
        return iter(self._cursor)

    @property
    def rowcount(self):
        return self._cursor.rowcount


class CompatConnection:
    def __init__(self, connection, postgres):
        self._connection = connection
        self._postgres = postgres

    def __enter__(self):
        self._connection.__enter__()
        return self

    def __exit__(self, exc_type, exc, tb):
        return self._connection.__exit__(exc_type, exc, tb)

    def close(self):
        return self._connection.close()

    def execute(self, sql, params=()):
        if not self._postgres:
            return self._connection.execute(sql, params)

        pragma = re.fullmatch(
            r"\s*PRAGMA\s+table_info\((\w+)\)\s*;?\s*",
            sql, flags=re.IGNORECASE
        )
        if pragma:
            table = pragma.group(1)
            cursor = self._connection.execute(
                """SELECT column_name AS name
                   FROM information_schema.columns
                   WHERE table_schema = current_schema() AND table_name = %s
                   ORDER BY ordinal_position""",
                (table,)
            )
            return CompatCursor(cursor)

        query = sql.strip()
        ignore_insert = bool(re.search(
            r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", query, re.IGNORECASE
        ))
        query = re.sub(
            r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", "INSERT INTO",
            query, flags=re.IGNORECASE
        )
        query = re.sub(
            r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            query, flags=re.IGNORECASE
        )
        query = re.sub(
            r"\s+COLLATE\s+NOCASE\b", "", query, flags=re.IGNORECASE
        )
        query = re.sub(
            r"ON\s+(\w+)\s*\(\s*(username|email)\s*\)",
            r"ON \1 (LOWER(\2))", query, flags=re.IGNORECASE
        )
        query = re.sub(
            r"\b(username|email)\s*=\s*\?",
            r"LOWER(\1) = LOWER(?)", query, flags=re.IGNORECASE
        )
        query = query.replace("?", "%s")

        query = query.rstrip().rstrip(";").rstrip()
        if ignore_insert and not re.search(r"\bON\s+CONFLICT\b", query, re.I):
            query += " ON CONFLICT DO NOTHING"

        wants_id = bool(re.match(
            r"\s*INSERT\s+INTO\s+(content|post_comments)\b",
            query, re.IGNORECASE
        ))
        if wants_id and " RETURNING " not in query.upper():
            query += " RETURNING id"

        try:
            cursor = self._connection.execute(query, params)
        except Exception as exc:
            try:
                import psycopg
                if isinstance(exc, psycopg.errors.UniqueViolation):
                    self._connection.rollback()
                    raise sqlite3.IntegrityError(str(exc)) from exc
            except ImportError:
                pass
            raise
        lastrowid = None
        if wants_id:
            row = cursor.fetchone()
            if row is not None:
                lastrowid = row["id"]
        return CompatCursor(cursor, lastrowid)


def connect_database(sqlite_path):
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        connection = sqlite3.connect(sqlite_path)
        connection.row_factory = sqlite3.Row
        return connection

    import psycopg

    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://"):]

    connection = psycopg.connect(url, row_factory=_hybrid_row_factory)
    return CompatConnection(connection, postgres=True)
